"""Stage 14 training engine — the single trainer behind Stages 15 to 18.

One Trainer drives every configuration: cWGAN-GP (critic + adversarial term)
and the plain U-Net L1 baseline (lambda_adv = 0, critic = null). Everything a
run needs to survive a node death is written every epoch:

  <run_dir>/checkpoints/last.pt    atomic (tmp + os.replace), full RNG state
  <run_dir>/checkpoints/best.pt    on val_ssim improvement
  <run_dir>/metrics.jsonl          one record per epoch, flushed and fsynced
  <run_dir>/samples/epoch_####.png sample grid every sample_every epochs
  <run_dir>/STOP                   touch it (or send SIGUSR1) for a clean exit

Split storage layout (.gitignore hides runs/, so the light,
citable side of a run is written into the repo as well):

  heavy artifacts -> $MUOGRAPHY_RUNS/<run_id>/ (default runs/<run_id>)
  tracked record  -> results/training/records/<run_id>/{config.json,
                     metrics.jsonl, summary.json}

Diagnostics logged per epoch (Stage 15 requires all of them): Wasserstein
estimate, gradient penalty, L1, adversarial term, E[D(real)], E[D(fake)],
gradient norms, across-batch output spread (mode collapse), the high-frequency
power ratio of the residual (checkerboard detector) and the train/val SSIM gap
(overfitting).

Overfit mode (Stage 14.5) trains on N FIXED pairs: hflip is forced off and only
a final checkpoint is written, since per-epoch checkpointing over a ~500
iteration budget would push ~100 GB of near-identical weights onto NFS.
"""

