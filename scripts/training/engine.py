def git_commit() -> str:
    try:
        out = subprocess.run(["git", "rev-parse", "--short", "HEAD"],
                             cwd=str(REPO_ROOT), capture_output=True, text=True,
                             timeout=10, check=True)
        return out.stdout.strip() or "unknown"
    except Exception:  # noqa: BLE001 — provenance is best-effort, never fatal
        return "unknown"


def strip_documentation_keys(config: dict) -> dict:
    """Drop the underscore keys: they document a config, they are not part of
    it. e15_reference.json carries "_comment" and the Stage 17 configuration
    generated by chain_driver.py carries a whole "_derivation" block — hashing
    a note about how a configuration was chosen into the identity of the runs
    that use it would make an edited comment look like a different experiment.
    """
    return {key: value for key, value in config.items()
            if not str(key).startswith("_")}


def config_sha8(config: dict) -> str:
    return hashlib.sha256(
        json.dumps(config, sort_keys=True).encode("utf-8")).hexdigest()[:8]


def resolve_device(name=None) -> torch.device:
    if name:
        return torch.device(name)
    return torch.device("cuda" if torch.cuda.is_available() else "cpu")


def grad_norm(parameters) -> float:
    total = 0.0
    for p in parameters:
        if p.grad is not None:
            total += float(p.grad.detach().norm(2).item()) ** 2
    return float(total ** 0.5)


def json_safe(value):
    """json.dumps writes bare NaN/Infinity, which strict parsers reject."""
    if isinstance(value, float):
        return value if math.isfinite(value) else None
    if isinstance(value, dict):
        return {key: json_safe(item) for key, item in value.items()}
    if isinstance(value, (list, tuple)):
        return [json_safe(item) for item in value]
    return value


def nyquist_ratio(residual: np.ndarray, ring: float = 0.45,
                  floor: float = 0.40) -> float:
    """High-frequency ring power over the low-frequency floor of the residual.

    ConvTranspose checkerboarding is a period-2 pattern: its energy sits at the
    EDGE of the spectrum (radius 1.0 along an axis, up to 1.414 diagonally),
    not near Nyquist/2. The diagnostic therefore compares the mean power above
    `ring` x Nyquist against the floor below `floor` x Nyquist, so every
    artifact geometry pushes the ratio UP and a rising value is the early
    warning the Stage 15 protocol asks for.
    """
    if residual.ndim == 4:
        residual = residual[:, 0]
    h, w = residual.shape[-2:]
    spectrum = np.fft.fftshift(np.fft.fft2(residual, axes=(-2, -1)), axes=(-2, -1))
    power = np.abs(spectrum) ** 2
    fy = np.fft.fftshift(np.fft.fftfreq(h)) / 0.5   # normalized to Nyquist
    fx = np.fft.fftshift(np.fft.fftfreq(w)) / 0.5
    radius = np.sqrt(fy[:, None] ** 2 + fx[None, :] ** 2)
    band = radius >= ring
    base = radius < floor
    if not band.any() or not base.any():
        return float("nan")
    denominator = float(power[..., base].mean())
    if denominator <= 0.0:
        return float("nan")
    return float(power[..., band].mean() / denominator)


class Trainer:
    """Train one configuration; resumable, interruptible, fully logged."""

    def __init__(self, config: dict, run_dir, datasets=None):
        config = strip_documentation_keys(dict(config))
        self.config = {**DEFAULT_CONFIG, **config}
        if isinstance(config.get("early_stop"), dict):
            # A partial early_stop dict (from --config JSON or --patience)
            # must not shadow the other early_stop keys via a shallow merge
            # -- that would KeyError on min_delta/metric later in train().
            self.config["early_stop"] = {**DEFAULT_CONFIG["early_stop"],
                                         **config["early_stop"]}
        if self.config["input_scaling"] == PLACEHOLDER_SCALING:
            raise ValueError(
                f"input_scaling is still the placeholder {PLACEHOLDER_SCALING!r}: "
                "the Stage 13.4 A/B decides it. Pass --input-scaling "
                f"{{{', '.join(INPUT_SCALINGS)}}} or edit the config.")
        if self.config["input_scaling"] not in INPUT_SCALINGS:
            raise ValueError(
                f"input_scaling must be one of {INPUT_SCALINGS}, "
                f"got {self.config['input_scaling']!r}")

        self.run_dir = Path(run_dir)
        self.run_id = str(self.config["run_id"])
        self.checkpoint_dir = self.run_dir / "checkpoints"
        self.sample_dir = self.run_dir / "samples"
        self.metrics_path = self.run_dir / "metrics.jsonl"
        self.stop_path = self.run_dir / "STOP"
        self.record_dir = RECORDS_DIR / self.run_id
        for path in (self.checkpoint_dir, self.sample_dir, self.record_dir):
            path.mkdir(parents=True, exist_ok=True)

        self.device = resolve_device(self.config["device"])
        self.seed = int(self.config["seed"])
        self.overfit_n = self.config["overfit_n"]
        self.max_iters = self.config["max_iters"]
        self.git_commit = git_commit()
        if self.overfit_n:
            # Stage 14.5 is "N FIXED pairs": mirroring would change the target
            # set the run is supposed to memorize, and so would re-thinning.
            self.config["hflip"] = False
            if self.config.get("rethin"):
                self.config["rethin"] = False
        self.config_sha8 = config_sha8(self.config)

        if self.device.type == "cuda":
            torch.backends.cudnn.benchmark = True  # shapes are fixed all night

        torch.manual_seed(self.seed)
        np.random.seed(self.seed % (2 ** 32))
        random.seed(self.seed)

        self._build_models()
        self._build_data(datasets)

        self.global_step = 0
        self.start_epoch = 0
        self.best_ssim = -float("inf")
        self.best_epoch = 0
        self.patience_counter = 0
        self._last_batch = None
        self._register_signal_handler()

        apply_style()
        self._write_json(self.record_dir / "config.json", self.describe())

    # ----------------------------------------------------------------- setup
    def _build_models(self) -> None:
        self.generator = build_generator(self.config["generator"]).to(self.device)
        self.opt_g = torch.optim.Adam(self.generator.parameters(),
                                      lr=float(self.config["lr"]),
                                      betas=tuple(self.config["betas"]))
        self.lambda_adv = float(self.config["lambda_adv"])
        use_critic = self.config["critic"] is not None and self.lambda_adv != 0.0
        if use_critic:
            self.critic = build_critic(self.config["critic"]).to(self.device)
            self.opt_c = torch.optim.Adam(self.critic.parameters(),
                                          lr=float(self.config["lr"]),
                                          betas=tuple(self.config["betas"]))
        else:
            self.critic = None
            self.opt_c = None

    def _build_data(self, datasets) -> None:
        fraction = float(self.config["fraction"])
        if datasets is not None:
            self.train_ds, self.val_ds = datasets
        else:
            # "rethin" is read with .get() and is deliberately ABSENT from
            # DEFAULT_CONFIG: adding a key to the default dict would change
            # config_sha8 for every existing configuration, and a run resumed
            # after that change would be refused by load_checkpoint. Only the
            # Stage 16 c11 arm carries the key, so only c11 gets a new hash.
            self.train_ds = MuographyPairs(
                split="train", fractions=[fraction],
                input_scaling=self.config["input_scaling"],
                hflip=bool(self.config["hflip"]), seed=self.seed,
                rethin=bool(self.config.get("rethin", False)))
            # Validation never re-thins: the early-stopping curve has to be
            # measured against a fixed set of pairs.
            self.val_ds = MuographyPairs(
                split="val", fractions=[fraction],
                input_scaling=self.config["input_scaling"], hflip=False)

        batch = int(self.config["batch"])
        drop_last = True
        if self.overfit_n:
            n = int(self.overfit_n)
            self.train_ds = Subset(self.train_ds, list(range(n)))
            # The overfit-10 criterion IS the train SSIM, so validation runs on
            # the same fixed pairs: a 360-pair val pass per iteration would
            # dominate the ~500-iteration budget for no diagnostic gain.
            self.val_ds = self.train_ds
            batch = min(batch, n)
            drop_last = False

        self._loader_generator = torch.Generator()
        self._loader_generator.manual_seed(self.seed)
        self.train_loader = DataLoader(
            self.train_ds, batch_size=batch, shuffle=True, num_workers=0,
            drop_last=drop_last, generator=self._loader_generator)
        self.val_loader = DataLoader(self.val_ds, batch_size=batch,
                                     shuffle=False, num_workers=0)
        if len(self.train_loader) == 0:
            raise ValueError(
                f"empty train loader: {len(self.train_ds)} pairs with "
                f"batch={batch} and drop_last={drop_last}")

    def _register_signal_handler(self) -> None:
        if not hasattr(signal, "SIGUSR1"):
            return  # Windows: use the STOP file instead

        def _on_usr1(signum, frame):  # noqa: ARG001
            self.stop_path.touch()

        try:
            signal.signal(signal.SIGUSR1, _on_usr1)
        except ValueError:  # not the main thread
            pass

    def describe(self) -> dict:
        info = {
            "run_id": self.run_id,
            # Storage location, not an experiment parameter: kept OUTSIDE
            # "config" so moving --out-root never changes config_sha8.
            "out_root": str(self.run_dir.parent),
            "config": self.config,
            "config_sha8": self.config_sha8,
            "device": str(self.device),
            "git_commit": self.git_commit,
            "generator_params": count_params(self.generator),
            "critic_params": count_params(self.critic) if self.critic else 0,
            "train_pairs": len(self.train_ds),
            "val_pairs": len(self.val_ds),
            "iterations_per_epoch": len(self.train_loader),
            "torch": torch.__version__,
        }
        return info

    # ------------------------------------------------------------- one step
    def train_step(self, cond: torch.Tensor, target: torch.Tensor,
                   capture: bool = True) -> dict:
        """One full iteration: n_critic critic steps, then one generator step.

        capture=False skips the host copy of the batch (the copy forces a
        device sync). The caller sets capture=True for the epoch's last
        iteration (nyquist/checkerboard diagnostics) and for every 10th
        iteration of a validation epoch (train_ssim_mean sampling).
        """
        cond = cond.to(self.device, non_blocking=True)
        target = target.to(self.device, non_blocking=True)
        parts = {"d_real": 0.0, "d_fake": 0.0, "w_est": 0.0, "gp": 0.0,
                 "grad_norm_d": 0.0}

        if self.critic is not None:
            n_critic = int(self.config["n_critic"])
            lambda_gp = float(self.config["lambda_gp"])
            # The generator does not change during the critic steps, so its
            # output is computed once and reused (bit-identical, ~15% faster).
            with torch.no_grad():
                fake = self.generator(cond)
            for _ in range(n_critic):
                loss_c, c_parts = critic_loss(self.critic, cond, target, fake,
                                              lambda_gp)
                self.opt_c.zero_grad(set_to_none=True)
                loss_c.backward()
                parts["grad_norm_d"] += grad_norm(self.critic.parameters()) / n_critic
                self.opt_c.step()
                for key in ("d_real", "d_fake", "w_est", "gp"):
                    parts[key] += c_parts[key] / n_critic

        fake = self.generator(cond)
        loss_g, g_parts = generator_loss(
            self.critic, cond, fake, target,
            lambda_l1=float(self.config["lambda_l1"]),
            lambda_adv=self.lambda_adv)
        self.opt_g.zero_grad(set_to_none=True)
        loss_g.backward()
        parts["grad_norm_g"] = grad_norm(self.generator.parameters())
        self.opt_g.step()

        parts.update(g_parts)
        self.global_step += 1
        if capture:
            self._last_batch = (fake.detach().cpu().numpy(),
                                target.detach().cpu().numpy())
        return parts

    # ------------------------------------------------------------ evaluation
    @torch.no_grad()
    def evaluate(self, loader) -> tuple:
        self.generator.eval()
        ssim_values, psnr_values = [], []
        for cond, target in loader:
            fake = self.generator(cond.to(self.device)).cpu().numpy()
            tgt = target.numpy()
            for j in range(fake.shape[0]):
                ssim_values.append(compute_ssim(fake[j, 0], tgt[j, 0]))
                psnr_values.append(compute_psnr(tgt[j, 0], fake[j, 0]))
        self.generator.train()
        return ssim_values, psnr_values

    def _batch_ssim(self) -> float:
        fake, target = self._last_batch
        return float(np.mean([compute_ssim(fake[j, 0], target[j, 0])
                              for j in range(fake.shape[0])]))

    # ----------------------------------------------------------- checkpoints
    def save_checkpoint(self, path: Path, epoch: int) -> None:
        payload = {
            "epoch": epoch,
            "global_step": self.global_step,
            "generator": self.generator.state_dict(),
            "critic": self.critic.state_dict() if self.critic else None,
            "opt_g": self.opt_g.state_dict(),
            "opt_c": self.opt_c.state_dict() if self.opt_c else None,
            "rng_torch": torch.get_rng_state(),
            "rng_torch_cuda": (torch.cuda.get_rng_state_all()
                               if torch.cuda.is_available() else None),
            "rng_numpy": np.random.get_state(),
            "rng_python": random.getstate(),
            "best_ssim": self.best_ssim,
            "best_epoch": self.best_epoch,
            "patience_counter": self.patience_counter,
            "config": self.config,
            "config_sha8": self.config_sha8,
            "git_commit": self.git_commit,
        }
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(path.suffix + ".tmp")
        # fsync the temporary file BEFORE the rename: os.replace is atomic on
        # the directory entry, not on the data still sitting in the page cache.
        with open(tmp, "wb") as handle:
            torch.save(payload, handle)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(tmp, path)

    def load_checkpoint(self, path: Path) -> int:
        # map_location="cpu": the saved CUDA RNG states must come back as CPU
        # ByteTensors for torch.cuda.set_rng_state_all; module and optimizer
        # load_state_dict move their own tensors to the live device.
        payload = torch.load(path, map_location="cpu", weights_only=False)
        stored_sha8 = payload.get("config_sha8")
        if stored_sha8 is not None and stored_sha8 != self.config_sha8:
            # Checkpoints written before strip_documentation_keys() hashed the
            # "_comment" of the config file along with the parameters. Their
            # PARAMETERS are identical to this run's, so refusing them would
            # strand a healthy in-flight run over a comment. Anything else is
            # still refused.
            stored_config = payload.get("config")
            documentation_only = (
                isinstance(stored_config, dict)
                and config_sha8(strip_documentation_keys(stored_config))
                == self.config_sha8)
            if not documentation_only:
                raise RuntimeError(
                    f"checkpoint {path} was written by config_sha8="
                    f"{stored_sha8} but this run is config_sha8="
                    f"{self.config_sha8}: resuming a different configuration "
                    "under the same run_id would make the record untraceable. "
                    "Use a new run_id or restore the config.")
            print(f"resuming {path.name} written as config_sha8={stored_sha8}: "
                  "the difference is documentation keys only, the parameters "
                  f"match config_sha8={self.config_sha8}")
        self.generator.load_state_dict(payload["generator"])
        self.opt_g.load_state_dict(payload["opt_g"])
        if self.critic is not None and payload.get("critic") is not None:
            self.critic.load_state_dict(payload["critic"])
            self.opt_c.load_state_dict(payload["opt_c"])
        torch.set_rng_state(payload["rng_torch"].cpu()
                            if hasattr(payload["rng_torch"], "cpu")
                            else payload["rng_torch"])
        if payload.get("rng_torch_cuda") is not None and torch.cuda.is_available():
            torch.cuda.set_rng_state_all(payload["rng_torch_cuda"])
        np.random.set_state(payload["rng_numpy"])
        random.setstate(payload["rng_python"])
        self.global_step = int(payload["global_step"])
        self.best_ssim = float(payload["best_ssim"])
        self.best_epoch = int(payload.get("best_epoch", 0))
        # Old checkpoints (in-flight cluster runs) predate this field: 0
        # restarts the count, matching their previous behavior exactly.
        self.patience_counter = int(payload.get("patience_counter", 0))
        return int(payload["epoch"])

    def resume(self) -> int:
        last = self.checkpoint_dir / "last.pt"
        if not last.exists():
            return 0
        epoch = self.load_checkpoint(last)
        self._truncate_metrics(epoch)
        print(f"resumed {self.run_id} from epoch {epoch} "
              f"(best val_ssim {self.best_ssim:.4f} at epoch {self.best_epoch})")
        return epoch

    def _refuse_resume_none_over_existing_run(self) -> None:
        """--resume none must never silently append duplicate epochs."""
        found = []
        if self.metrics_path.exists():
            found.append("metrics.jsonl")
        if any(self.checkpoint_dir.iterdir()):
            found.append("checkpoints")
        if found:
            raise RuntimeError(
                f"run_dir {self.run_dir} already has {' and '.join(found)} "
                f"for run_id={self.run_id!r}, but --resume none was "
                "requested. Pass a new --run-id or use --resume auto to "
                "continue this run -- starting fresh here would silently "
                "append duplicate epochs.")

    # ---------------------------------------------------------------- output
    @staticmethod
    def _write_json(path: Path, payload: dict) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(json_safe(payload), indent=2, default=str),
                        encoding="utf-8")

    def _truncate_metrics(self, last_epoch: int) -> None:
        if not self.metrics_path.exists():
            return
        kept = []
        for line in self.metrics_path.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            try:
                record = json.loads(line)
            except json.JSONDecodeError:
                continue
            if int(record.get("epoch", 0)) <= last_epoch:
                kept.append(line)
        self.metrics_path.write_text("\n".join(kept) + ("\n" if kept else ""),
                                     encoding="utf-8")
        self._mirror_metrics()

    def _mirror_metrics(self) -> None:
        """Keep the tracked copy of metrics.jsonl in sync with the run dir.

        Atomic: the mirror is rewritten whole every epoch, and it is what the
        chain driver reads to decide. A node death in the middle of the write
        would leave the driver reading a truncated history.
        """
        if not self.metrics_path.exists():
            return
        target = self.record_dir / "metrics.jsonl"
        tmp = target.with_suffix(".jsonl.tmp")
        with open(tmp, "w", encoding="utf-8") as handle:
            handle.write(self.metrics_path.read_text(encoding="utf-8"))
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(tmp, target)

    def _append_metrics(self, record: dict) -> None:
        with self.metrics_path.open("a", encoding="utf-8") as handle:
            handle.write(json.dumps(json_safe(record)) + "\n")
            handle.flush()
            os.fsync(handle.fileno())
        self._mirror_metrics()

    def _save_samples(self, epoch: int) -> None:
        n = min(4, len(self.val_ds))
        fig, axes = plt.subplots(n, 3, figsize=(9, 3.0 * n), squeeze=False)
        self.generator.eval()
        with torch.no_grad():
            for row in range(n):
                cond, target = self.val_ds[row]
                fake = self.generator(cond.unsqueeze(0).to(self.device))[0, 0]
                panels = (("Entrada", cond[0].numpy()),
                          ("Predicción", fake.cpu().numpy()),
                          ("Referencia", target[0].numpy()))
                for col, (title, image) in enumerate(panels):
                    ax = axes[row][col]
                    ax.imshow(image, origin="lower", vmin=0.0, vmax=1.0)
                    ax.set_xticks([])
                    ax.set_yticks([])
                    if row == 0:
                        ax.set_title(title)
        self.generator.train()
        fig.suptitle(f"{self.run_id} — época {epoch}")
        fig.savefig(self.sample_dir / f"epoch_{epoch:04d}.png")
        plt.close(fig)

    # ------------------------------------------------------------------ loop
    def train(self, resume: str = "auto") -> dict:
        if resume == "none":
            self._refuse_resume_none_over_existing_run()
        elif resume == "auto":
            self.start_epoch = self.resume()
        # A STOP left behind by a previous graceful exit would make this run
        # finish at epoch 1 with status done.
        self.stop_path.unlink(missing_ok=True)
        epochs = int(self.config["epochs"])
        patience = int(self.config["early_stop"]["patience"])
        min_delta = float(self.config["early_stop"]["min_delta"])
        val_every = int(self.config["val_every"])
        sample_every = int(self.config["sample_every"])
        early_stop_enabled = not self.overfit_n
        # Overfit runs burn hundreds of one-iteration epochs over a handful of
        # fixed pairs; a per-epoch checkpoint would write ~100 GB to NFS for
        # weights nobody reads. One checkpoint at the end is enough.
        checkpoint_each_epoch = not self.overfit_n

        print(json.dumps(self.describe(), indent=2, default=str))
        wall0 = time.perf_counter()
        stop_reason = "epochs"
        epoch = self.start_epoch

        for epoch in range(self.start_epoch + 1, epochs + 1):
            if self.stop_path.exists():
                stop_reason = "stop_file"
                break
            if self.max_iters is not None and self.global_step >= int(self.max_iters):
                stop_reason = "max_iters"
                break

            t_epoch = time.perf_counter()
            self._loader_generator.manual_seed(self.seed + epoch)
            base = getattr(self.train_ds, "dataset", self.train_ds)
            if hasattr(base, "set_epoch"):
                base.set_epoch(epoch)

            will_validate = (epoch % val_every == 0)
            totals: dict = {}
            train_ssim_samples: list = []
            n_iters = 0
            n_batches = len(self.train_loader)
            for i, (cond, target) in enumerate(self.train_loader):
                will_stop = (self.max_iters is not None
                             and self.global_step + 1 >= int(self.max_iters))
                # Every 10th iteration of a validation epoch doubles as a
                # train-SSIM sample: a single last-batch reading (n=8) has
                # scatter of the same order as the 0.05 train/val gap
                # threshold it feeds.
                sample_ssim = will_validate and (i % 10 == 0)
                parts = self.train_step(
                    cond, target,
                    capture=(i == n_batches - 1) or will_stop or sample_ssim)
                for key, value in parts.items():
                    totals[key] = totals.get(key, 0.0) + value
                n_iters += 1
                if sample_ssim:
                    train_ssim_samples.append(self._batch_ssim())
                if self.max_iters is not None and self.global_step >= int(self.max_iters):
                    stop_reason = "max_iters"
                    break
            means = {key: value / max(n_iters, 1) for key, value in totals.items()}

            fake, target_np = self._last_batch
            record = {
                "epoch": epoch,
                "global_step": self.global_step,
                "iterations": n_iters,
                "w_est": round(means.get("w_est", 0.0), 6),
                "gp": round(means.get("gp", 0.0), 6),
                "l1": round(means.get("l1", 0.0), 6),
                "adv": round(means.get("adv", 0.0), 6),
                "d_real": round(means.get("d_real", 0.0), 6),
                "d_fake": round(means.get("d_fake", 0.0), 6),
                "grad_norm_g": round(means.get("grad_norm_g", 0.0), 6),
                "grad_norm_d": round(means.get("grad_norm_d", 0.0), 6),
                # Spread ACROSS the batch: a collapsed generator ignores its
                # condition and emits the same image for every input.
                "out_std": round(float(fake.std(axis=0).mean()), 6),
                "nyquist_ratio": round(nyquist_ratio(fake - target_np), 6),
            }

            improved = False
            if will_validate:
                ssim_values, psnr_values = self.evaluate(self.val_loader)
                ssim = summarize(ssim_values)
                psnr = summarize(psnr_values, digits=2)
                train_batch_ssim = self._batch_ssim()
                train_ssim_mean = (float(np.mean(train_ssim_samples))
                                   if train_ssim_samples else train_batch_ssim)
                record.update({
                    "val_ssim": ssim["mean"],
                    "val_ssim_std": ssim["std"],
                    "val_psnr": psnr["mean"],
                    "val_psnr_std": psnr["std"],
                    "val_n": ssim["n"],
                    "train_batch_ssim": round(train_batch_ssim, 4),
                    "train_ssim_mean": round(train_ssim_mean, 4),
                    "train_val_gap": round(train_ssim_mean - ssim["mean"], 4),
                })
                if ssim["mean"] > self.best_ssim + min_delta:
                    self.best_ssim = ssim["mean"]
                    self.best_epoch = epoch
                    improved = True
                    self.patience_counter = 0
                else:
                    self.patience_counter += 1

            record["epoch_seconds"] = round(time.perf_counter() - t_epoch, 2)
            self._append_metrics(record)
            print(json.dumps(record), flush=True)

            if checkpoint_each_epoch:
                self.save_checkpoint(self.checkpoint_dir / "last.pt", epoch)
                if improved:
                    self.save_checkpoint(self.checkpoint_dir / "best.pt", epoch)
            if sample_every and epoch % sample_every == 0:
                self._save_samples(epoch)

            if self.stop_path.exists():
                stop_reason = "stop_file"
                break
            if early_stop_enabled and self.patience_counter >= patience:
                stop_reason = "early_stop"
                break
            if stop_reason == "max_iters":
                break

        if not checkpoint_each_epoch and epoch > self.start_epoch:
            self.save_checkpoint(self.checkpoint_dir / "last.pt", epoch)

        summary = {
            "run_id": self.run_id,
            "status": "done",
            "stop_reason": stop_reason,
            # Storage location, not an experiment parameter: kept OUTSIDE
            # "config" so moving --out-root never changes config_sha8.
            "out_root": str(self.run_dir.parent),
            "config_sha8": self.config_sha8,
            "best_val_ssim": (self.best_ssim if np.isfinite(self.best_ssim)
                              else None),
            "best_epoch": self.best_epoch,
            "epochs_run": max(epoch - self.start_epoch, 0),
            "last_epoch": epoch,
            "global_step": self.global_step,
            "overfit_n": self.overfit_n,
            "wall_seconds": round(time.perf_counter() - wall0, 1),
            "git_commit": self.git_commit,
            "config": self.config,
        }
        self._write_json(self.record_dir / "summary.json", summary)
        self._write_json(self.run_dir / "summary.json", summary)
        return summary


def run_dir_for(run_id: str, out_root=None) -> Path:
    root = Path(out_root) if out_root else Path(
        os.environ.get("MUOGRAPHY_RUNS", str(DEFAULT_RUNS_DIR)))
    return root / run_id
